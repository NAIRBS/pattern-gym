"""Generate the Bug Hunt items: content/bug_hunt_data.py.

For every reference solution, try each mutation in content/bug_hunt.py on each line (key lines first) and keep a
bug only if the visible tests then fail (wrong answer or an error) without timing out. Up to 2 bugs per problem,
of different kinds. Run:  python make_bugs.py   (takes a few minutes; validate.py re-checks the result)
"""
import os
import sys
from concurrent.futures import ThreadPoolExecutor

ROOT = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, ROOT)
from content import load_all  # noqa: E402
from content.bug_hunt import mutants, apply  # noqa: E402
from server import run_code  # noqa: E402

PER_PROBLEM = 2
# Rarer kinds first, so the set isn't all boundary bugs
PREFER = ["aliasing", "scope", "heap_sign", "wrong_end", "bad_start", "int_div", "missing_update", "min_max",
          "and_or", "bool_return", "off_by_one", "boundary"]


def candidates(p):
    lines = p["solution"].split("\n")
    order = list(p["key_lines"]) + [i for i in range(len(lines)) if i not in p["key_lines"]]
    out = []
    for i in order:
        for kind, new in mutants(lines, i):
            out.append({"problem": p["id"], "line": i, "fixed": lines[i], "buggy": new, "kind": kind, "key": i in p["key_lines"]})
    out.sort(key=lambda b: (not b["key"], PREFER.index(b["kind"])))
    return out


def fails(p, bug):
    spec = {k: v for k, v in p["tests"].items() if k != "perf"}
    r = run_code(apply(p["solution"], bug), spec, timeout=3)
    if "Time limit" in (r.get("error") or ""):
        return False
    return not r.get("ok")


def pick(p):
    chosen, kinds = [], set()
    for b in candidates(p):
        if len(chosen) >= PER_PROBLEM:
            break
        if b["kind"] in kinds:
            continue
        if fails(p, b):
            chosen.append(b)
            kinds.add(b["kind"])
    for k, b in enumerate(chosen):
        b["id"] = f"{p['id']}-{k + 1}"
        del b["key"]
    return chosen


def main():
    probs = load_all()["problems"]
    with ThreadPoolExecutor(8) as ex:
        found = list(ex.map(pick, probs))
    bugs = [b for bs in found for b in bs]
    with open(os.path.join(ROOT, "content", "bug_hunt_data.py"), "w", encoding="utf-8", newline="\n") as f:
        f.write('"""Generated by make_bugs.py. Do not edit by hand: run `python make_bugs.py` again."""\n')
        f.write("BUGS = [\n")
        for b in bugs:
            f.write("    " + repr({k: b[k] for k in ("id", "problem", "line", "kind", "fixed", "buggy")}) + ",\n")
        f.write("]\n")
    from collections import Counter
    print(f"{len(bugs)} bugs in {sum(1 for x in found if x)} of {len(probs)} problems:", dict(Counter(b["kind"] for b in bugs)))


if __name__ == "__main__":
    main()
